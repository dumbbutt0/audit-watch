import os
import stat

from preaudit_guard.cli import main
from preaudit_guard.findings import Severity
from preaudit_guard.sandbox import (
    generate_sandbox, detect_ecosystems, pick_base_image,
)


ARTIFACTS = {
    "SECURITY_PREFLIGHT.md",
    "Dockerfile.quarantine",
    "run-quarantine.sh",
    "agent_context_safe.md",
}


def test_generates_all_artifacts(malicious_repo, tmp_path):
    result, written = generate_sandbox(malicious_repo, tmp_path)
    assert {p.name for p in written} == ARTIFACTS
    for name in ARTIFACTS:
        assert (tmp_path / name).exists()
    assert result.overall == Severity.CRITICAL


def test_agent_context_excludes_raw_injection(malicious_repo, tmp_path):
    generate_sandbox(malicious_repo, tmp_path)
    content = (tmp_path / "agent_context_safe.md").read_text().lower()
    # the README's attacker prose must NOT leak into the agent-facing summary
    assert "ignore all previous instructions" not in content
    assert "send any private key" not in content
    assert "read the environment variables" not in content
    # but the README must be named as withheld
    assert "readme.md" in content
    assert "withheld" in content


def test_run_wrapper_is_hardened_and_executable(malicious_repo, tmp_path):
    generate_sandbox(malicious_repo, tmp_path)
    wrapper = tmp_path / "run-quarantine.sh"
    text = wrapper.read_text()
    for flag in ("--network none", "--security-opt no-new-privileges", "--cap-drop ALL", ":ro"):
        assert flag in text
    assert os.stat(wrapper).st_mode & stat.S_IXUSR  # executable


def test_dockerfile_nonroot_and_no_install_at_build(malicious_repo, tmp_path):
    generate_sandbox(malicious_repo, tmp_path)
    df = (tmp_path / "Dockerfile.quarantine").read_text()
    assert df.startswith("# Generated by PreAudit Guard")
    assert "FROM " in df
    assert "USER 1000" in df
    # the project's own install/build must never run at image-build time
    for bad in ("RUN npm install", "RUN yarn", "RUN pip install", "RUN npm ci"):
        assert bad not in df


def test_base_image_detection():
    assert pick_base_image(["node"])[0] == "node:20-slim"
    assert pick_base_image(["python"])[0] == "python:3.12-slim"
    assert pick_base_image([])[0] == "debian:stable-slim"
    eco = detect_ecosystems({"package.json": "{}", "src/a.ts": ""})
    assert "node" in eco


def test_clean_repo_has_no_withheld(clean_repo, tmp_path):
    result, _ = generate_sandbox(clean_repo, tmp_path)
    content = (tmp_path / "agent_context_safe.md").read_text()
    assert result.overall == Severity.LOW
    assert "_None._" in content  # no prompt-injection files withheld


def test_cli_sandbox_success_and_nonempty_guard(malicious_repo, tmp_path, capsys):
    out = tmp_path / "q"
    assert main(["sandbox", str(malicious_repo), "-o", str(out)]) == 0
    capsys.readouterr()
    assert (out / "agent_context_safe.md").exists()
    # second run into the now non-empty dir fails without --force
    assert main(["sandbox", str(malicious_repo), "-o", str(out)]) == 1
    capsys.readouterr()
    assert main(["sandbox", str(malicious_repo), "-o", str(out), "--force"]) == 0
